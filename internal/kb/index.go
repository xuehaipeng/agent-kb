package kb

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

const (
	rootIndexMaxLines = 60
	dirIndexMaxLines  = 200
)

// IndexFiles renders the hierarchical indexes, keyed by path relative to
// s.Dir: a root index.md, one per project (hub mode), and one per type
// directory. Output depends only on file contents (never the clock or git
// HEAD), so two machines regenerate identical bytes and merges stay clean.
func (s *Store) IndexFiles() (map[string][]byte, error) {
	nodes, err := s.Nodes()
	if err != nil {
		return nil, err
	}
	sup := s.supersededIndex()
	byBundle := map[string][]*Node{}
	for _, n := range nodes {
		byBundle[n.Project] = append(byBundle[n.Project], n)
	}
	out := map[string][]byte{}
	type row struct {
		name, link                      string
		active, trusted, unver, dispute int
		openReviews                     int
	}
	var rows []row
	var attention []string
	for _, b := range s.Bundles() {
		prefix := ""
		if s.Hub {
			rel, _ := filepath.Rel(s.Dir, b.Dir)
			prefix = filepath.ToSlash(rel) + "/"
		}
		body, stats, att := s.bundleIndex(b, byBundle[b.Project], sup, prefix, out)
		rows = append(rows, row{name: b.Project, link: prefix + "index.md", active: stats[0], trusted: stats[1], unver: stats[2], dispute: stats[3], openReviews: stats[4]})
		attention = append(attention, att...)
		if s.Hub {
			out[prefix+"index.md"] = []byte(body)
		} else {
			out["index.md"] = []byte(body)
		}
	}
	if s.Hub {
		var root strings.Builder
		root.WriteString("# Knowledge hub\n\n")
		root.WriteString("_Generated by `kb index`; do not edit. `kb search` scopes to the current repo's project plus global; `--all` searches every project._\n\n")
		root.WriteString("| Project | Active | Verified | Unverified | Disputed | Open reviews |\n|---|---|---|---|---|---|\n")
		pfs := s.ProjectFiles()
		for _, r := range rows {
			name := r.name
			if pf, ok := pfs[r.name]; ok && len(pf.Repos) > 0 {
				name += " (" + strings.Join(pf.Repos, ", ") + ")"
			}
			fmt.Fprintf(&root, "| [%s](%s) | %d | %d | %d | %d | %d |\n", name, r.link, r.active, r.trusted, r.unver, r.dispute, r.openReviews)
		}
		writeAttention(&root, attention)
		out["index.md"] = []byte(root.String())
	}
	return out, nil
}

// bundleIndex renders one bundle's index.md and its type-directory indexes.
// stats: active, verified-or-better, unverified, disputed, open reviews.
func (s *Store) bundleIndex(b Bundle, list []*Node, sup map[string]string, prefix string, out map[string][]byte) (string, [5]int, []string) {
	var stats [5]int
	byType := map[string][]*Node{}
	for _, n := range list {
		byType[n.TypeKey] = append(byType[n.TypeKey], n)
	}
	var root strings.Builder
	switch {
	case !s.Hub:
		root.WriteString("# Knowledge index\n\n")
	case b.Project == GlobalProject:
		root.WriteString("# Global knowledge\n\nShared by every project. Entries may list the `projects` they apply to.\n\n")
	default:
		fmt.Fprintf(&root, "# Project: %s\n\n", b.Project)
	}
	root.WriteString("_Generated by `kb index`; do not edit. Search with `kb search`, read with `kb show <id>`._\n\n")
	root.WriteString("| Section | Active | Verified | Unverified | Disputed |\n|---|---|---|---|---|\n")
	var attention []string
	for _, tk := range s.Cfg.TypeNames() {
		tc := s.Cfg.Types[tk]
		items := byType[tk]
		if tk == "review" {
			open := 0
			for _, n := range items {
				if st, _ := s.ReviewState(n); st == ReviewPending || st == ReviewChanges {
					open++
				}
			}
			stats[4] += open
			fmt.Fprintf(&root, "| [%s](%s/index.md) | %d open | | | |\n", DisplayType(tc.Dir), tc.Dir, open)
			out[prefix+tc.Dir+"/index.md"] = []byte(s.reviewIndex(tk, items))
			continue
		}
		var active, trusted, unv, disp int
		for _, n := range items {
			t := s.TrustStatic(n, sup)
			switch {
			case t.State == StateDeprecated:
				continue
			case t.Trusted():
				trusted++
			case t.State == StateUnverified:
				unv++
			case t.State == StateDisputed:
				disp++
				attention = append(attention, fmt.Sprintf("* [%s](%s%s.md) - disputed (%s)", n.Meta().Title, prefix, n.LocalID(), strings.Join(t.Disputers, ", ")))
			}
			active++
		}
		stats[0] += active
		stats[1] += trusted
		stats[2] += unv
		stats[3] += disp
		fmt.Fprintf(&root, "| [%s](%s/index.md) | %d | %d | %d | %d |\n", DisplayType(tc.Dir), tc.Dir, active, trusted, unv, disp)
		out[prefix+tc.Dir+"/index.md"] = []byte(s.dirIndex(tk, items, sup))
	}
	if !s.Hub {
		writeAttention(&root, attention)
	}
	return root.String(), stats, attention
}

func writeAttention(b *strings.Builder, attention []string) {
	if len(attention) == 0 {
		return
	}
	b.WriteString("\n## Disputed\n\n")
	sort.Strings(attention)
	max := rootIndexMaxLines - strings.Count(b.String(), "\n") - 2
	if max < 3 {
		max = 3
	}
	if len(attention) > max {
		extra := len(attention) - max
		attention = append(attention[:max], fmt.Sprintf("* ... %d more: `kb status`", extra))
	}
	b.WriteString(strings.Join(attention, "\n") + "\n")
}

func (s *Store) dirIndex(tk string, list []*Node, sup map[string]string) string {
	tc := s.Cfg.Types[tk]
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", DisplayType(tc.Dir))
	if tc.Description != "" {
		b.WriteString(tc.Description + "\n\n")
	}
	b.WriteString("_Generated by `kb index`; do not edit._\n\n")
	sorted := append([]*Node(nil), list...)
	sort.SliceStable(sorted, func(i, j int) bool {
		return strings.ToLower(sorted[i].Meta().Title) < strings.ToLower(sorted[j].Meta().Title)
	})
	var active, deprecated []string
	for _, n := range sorted {
		t := s.TrustStatic(n, sup)
		rel := strings.TrimPrefix(n.LocalID(), tc.Dir+"/") + ".md"
		if t.State == StateDeprecated {
			note := ""
			if t.SupersededBy != "" {
				note = " (superseded by " + t.SupersededBy + ")"
			}
			deprecated = append(deprecated, fmt.Sprintf("* [%s](%s)%s", n.Meta().Title, rel, note))
			continue
		}
		active = append(active, fmt.Sprintf("* [%s](%s) - %s `%s`", n.Meta().Title, rel, oneLine(n.Meta().Description, 140), t.State))
	}
	budget := dirIndexMaxLines - strings.Count(b.String(), "\n") - 4
	if len(active) == 0 {
		b.WriteString("_No active entries._\n")
	}
	if len(active) > budget {
		extra := len(active) - budget
		active = append(active[:budget], fmt.Sprintf("* ... %d more: use `kb search`", extra))
	}
	if len(active) > 0 {
		b.WriteString(strings.Join(active, "\n") + "\n")
	}
	budget -= len(active)
	if len(deprecated) > 0 && budget > 3 {
		b.WriteString("\n## Deprecated\n\n")
		if len(deprecated) > budget-2 {
			extra := len(deprecated) - (budget - 2)
			deprecated = append(deprecated[:budget-2], fmt.Sprintf("* ... %d more", extra))
		}
		b.WriteString(strings.Join(deprecated, "\n") + "\n")
	}
	return b.String()
}

func (s *Store) reviewIndex(tk string, list []*Node) string {
	tc := s.Cfg.Types[tk]
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n_Generated by `kb index`; do not edit. Use `kb review list`._\n\n", DisplayType(tc.Dir))
	sorted := append([]*Node(nil), list...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].ID > sorted[j].ID })
	var open, done []string
	for _, n := range sorted {
		st, _ := s.ReviewState(n)
		rel := strings.TrimPrefix(n.LocalID(), tc.Dir+"/") + ".md"
		line := fmt.Sprintf("* [%s](%s) - by %s `%s`", n.Meta().Title, rel, n.Meta().Generated.By, st)
		if st == ReviewPending || st == ReviewChanges {
			open = append(open, line)
		} else {
			done = append(done, line)
		}
	}
	b.WriteString("## Open\n\n")
	if len(open) == 0 {
		b.WriteString("_None._\n")
	} else {
		b.WriteString(strings.Join(open, "\n") + "\n")
	}
	if len(done) > 0 {
		limit := dirIndexMaxLines - len(open) - 12
		if limit < 5 {
			limit = 5
		}
		if len(done) > limit {
			extra := len(done) - limit
			done = append(done[:limit], fmt.Sprintf("* ... %d more", extra))
		}
		b.WriteString("\n## Done\n\n" + strings.Join(done, "\n") + "\n")
	}
	return b.String()
}

// WriteIndex regenerates all index files and returns the ones that changed.
func (s *Store) WriteIndex() ([]string, error) {
	files, err := s.IndexFiles()
	if err != nil {
		return nil, err
	}
	var changed []string
	keys := make([]string, 0, len(files))
	for k := range files {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, rel := range keys {
		ok, err := WriteFileIfChanged(filepath.Join(s.Dir, filepath.FromSlash(rel)), files[rel])
		if err != nil {
			return changed, err
		}
		if ok {
			changed = append(changed, rel)
		}
	}
	return changed, nil
}
